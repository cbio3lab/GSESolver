import pandas as pd
AqSolDB = pd.read_csv('AqSolDBc_noions.csv')
BigSolDB = pd.read_csv('BigSolDBv2.0_w_298K_noions.csv')
avdeef = pd.read_csv('Avdeef_sol_db_298K.csv')
logP = pd.read_csv('logPN_final.csv')
cbio3 = pd.read_csv('SolCbio3Database_merged.csv')

"""## Check for matching smiles standard

### Subtask:
Compare the `SMILES_standard` column in `AqSolDB` with the `SMILES_standard` column in `cbio3`.

**Reasoning**:
Create a boolean Series indicating whether each `SMILES_standard` in `AqSolDB` is present in the `SMILES_standard` column of `cbio3`.
"""

is_present = AqSolDB['SMILES_standard'].isin(cbio3['smiles'])

"""## Identify non-matching entries

### Subtask:
Find the rows in `AqSolDB` where the `SMILES_standard` does not exist in `cbio3`.

**Reasoning**:
Filter the AqSolDB DataFrame using the boolean Series `is_present` to get rows where the SMILES_standard is not in cbio3 and store the result in a new DataFrame.
"""

AqSolDB_new_entries = AqSolDB[~is_present].copy()

"""## Prepare data for merging

### Subtask:
Select the relevant columns (`ID`, `Solubility`, `SMILEScurated`, and `SMILES_standard`) from the non-matching rows in `AqSolDB` and rename them to match the column names in `cbio3` (`Compound`, `logS`, `smiles`, and `SMILES_standard`).

**Reasoning**:
Select and rename the specified columns from the `AqSolDB_new_entries` DataFrame to match the column names in `cbio3`.
"""

AqSolDB_prepared = AqSolDB_new_entries[['ID', 'Solubility', 'SMILEScurated', 'SMILES_standard']].rename(columns={
    'ID': 'Compound',
    'Solubility': 'logS',
    'SMILES_standard': 'smiles'
})

"""## Set `ref logs` for new entries

### Subtask:
For the prepared data from `AqSolDB`, set the value in the `Ref_logS` column to the string "AqSolDB".

**Reasoning**:
Add a new column 'Ref_logS' to the `AqSolDB_prepared` DataFrame and set its value to "AqSolDB" for all rows as per the instructions. Then, display the head of the DataFrame to verify the changes.
"""

AqSolDB_prepared['Ref_logS'] = "AqSolDB"

"""## Merge dataframes

### Subtask:
Append the prepared data from `AqSolDB` to `cbio3`.

**Reasoning**:
Concatenate the two dataframes and display the head of the resulting dataframe.
"""

cbio3_updated = pd.concat([cbio3, AqSolDB_prepared], ignore_index=True)
cbio3_updated

"""## Check for matching smiles standard in bigsoldb

### Subtask:
Compare the `SMILES_standard` column in `BigSolDB` with the `SMILES_standard` column in the `cbio3_updated` DataFrame.

**Reasoning**:
Create a boolean Series indicating whether each SMILES_standard in BigSolDB is present in the SMILES_standard column of cbio3_updated and store it in a new variable.
"""

is_present_bigsol = BigSolDB['SMILES_standard'].isin(cbio3_updated['smiles'])

"""## Identify non-matching entries in bigsoldb

### Subtask:
Find the rows in `BigSolDB` where the `SMILES_standard` does not exist in `cbio3_updated`.

**Reasoning**:
Filter the BigSolDB DataFrame to find rows where the SMILES_standard is not present in cbio3_updated and display the head of the resulting DataFrame.
"""

BigSolDB_new_entries = BigSolDB[~is_present_bigsol].copy()

"""## Prepare data from bigsoldb for merging

### Subtask:
Select the relevant columns (`Compound_name`, `CAS`, `SMILES_Solute`, and `LogS(mol/L)`) from the non-matching rows in `BigSolDB` and rename them to match the column names in `cbio3_updated` (`Compound`, `CAS_RN`, `smiles`, and `logS`).

**Reasoning**:
Select and rename the specified columns from the `BigSolDB_new_entries` DataFrame to match the column names in `cbio3_updated` and display the head of the resulting DataFrame.
"""

BigSolDB_prepared = BigSolDB_new_entries[['Compound_Name', 'CAS', 'SMILES_Solute','SMILES_standard', 'LogS(mol/L)']].rename(columns={
    'Compound_Name': 'Compound',
    'CAS': 'CAS_RN',
    'SMILES_Solute': 'smiles',
    'LogS(mol/L)': 'logS'
})

"""**Reasoning**:
Based on the column names, the correct column for the compound name is 'Compound_Name'. Now, select the relevant columns ('Compound_Name', 'CAS', 'SMILES_Solute', and 'LogS(mol/L)') from the non-matching rows in `BigSolDB` and rename them to match the column names in `cbio3_updated` ('Compound', 'CAS_RN', 'smiles', and 'logS'), store the result in `BigSolDB_prepared`, and display the head.

## Set `ref logs` for new entries from bigsoldb

### Subtask:
For the prepared data from `BigSolDB`, set the value in the `Ref_logS` column to the string "BigSolDB2.0".

**Reasoning**:
Add the 'Ref_logS' column to the BigSolDB_prepared DataFrame and set its values to "BigSolDB2.0", then display the head of the updated DataFrame.
"""

BigSolDB_prepared['Ref_logS'] = "BigSolDB2.0"

BigSolDB_prepared

"""## Merge dataframes

### Subtask:
Append the prepared data from `BigSolDB` to `cbio3_updated`.

**Reasoning**:
Concatenate the two dataframes and display the head of the resulting dataframe.
"""

cbio3_final_updated = pd.concat([cbio3_updated, BigSolDB_prepared], ignore_index=True)
cbio3_final_updated


is_present_avdeef = avdeef['SMILES_standard'].isin(cbio3_final_updated['smiles'])
avdeef_new_entries = avdeef[~is_present_avdeef].copy()
avdeef_prepared = avdeef_new_entries[['Name', 'SMILES_standard', 'logS0_t', 'mp']].rename(columns={
    'Name': 'Compound',
    'SMILES_standard': 'smiles',
    'logS0_t': 'logS',
    'mp': 'mp'
})
avdeef_prepared['Ref_logS'] = "avdeef"

cbio3_final_updated = pd.concat([cbio3_final_updated, avdeef_prepared], ignore_index=True)




"""## Identify rows with missing logpn

### Subtask:
Filter the `cbio3_final_updated` DataFrame to find rows where the 'logPN' column is empty.

**Reasoning**:
Filter the `cbio3_final_updated` DataFrame to find rows where the 'logPN' column is empty and store the result in `cbio3_missing_logpn`.
"""

cbio3_missing_logpn = cbio3_final_updated[cbio3_final_updated['logPN'].isnull()].copy()

"""**Reasoning**:
The subtask of filtering rows with empty 'logPN' is complete. The next step is to check if the 'SMILES_standard' in these rows exist in the 'SMILES_standard' column of the `logP` DataFrame.


"""

is_present_logP = cbio3_missing_logpn['smiles'].isin(logP['SMILES_standard'])

"""**Reasoning**:
For the rows in `cbio3_missing_logpn` where the 'SMILES_standard' is present in `logP`, update the 'logPN' column with the corresponding 'logP' value from `logP` and set the 'Ref_logP' column to "Kenneth".


"""

cbio3_missing_logpn_with_logp = cbio3_missing_logpn[is_present_logP].copy()
merged_logp = pd.merge(cbio3_missing_logpn_with_logp[['SMILES_standard']],
                       logP[['SMILES_standard', 'logP']],
                       on='SMILES_standard',
                       how='left')

cbio3_final_updated.loc[cbio3_missing_logpn_with_logp.index, 'logPN'] = merged_logp['logP'].values
cbio3_final_updated.loc[cbio3_missing_logpn_with_logp.index, 'Ref_logP'] = "Kenneth"

cbio3_final_updated.loc[cbio3_missing_logpn_with_logp.index]

"""## Combine updated rows with original dataframe

### Subtask:
Combine the updated rows with the rows in `cbio3_final_updated` that did not have missing 'logPN' values.

## Save the updated dataframe

### Subtask:
Save the modified `cbio3_final_updated` dataframe to a new CSV file.

**Reasoning**:
Save the final updated dataframe to a CSV file without the index.
"""

cbio3_final_updated.to_csv("SolCbio3Database_merged_avdeef.csv", index=False)